// (저작권 라이선스 문제로 회계감사기준처럼 전문 텍스트를 그대로 수록할 수 없음). 따라서
// 원문을 우리 서버에 수록하는 대신, KAM 카테고리별로 실무에서 실제로 관련되는 기준서
// 번호·제목을 고정 매핑으로 안내하고, 각 기준서 원문은 한국회계기준원(KASB) 저작권
// 이용 승인을 받아 제공하는 삼일아이닷컴 외부 페이지로 링크한다.

export type IfrsRef = { code: string; title: string; url: string };

function samili(standardNo: string): string {
  return `https://www.samili.com/acc/Kijun/Kijunjomun.asp?code=1978-${standardNo}`;
}

